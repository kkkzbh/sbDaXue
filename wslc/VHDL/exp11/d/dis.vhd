--------------------------------------------------------------------------------
-- 文件名称: dis.vhd
-- 功能描述: 6位数码管滚动显示学号
-- 设计说明: 
--   1. 使用动态扫描方式驱动6位共阴极数码管
--   2. 学号 20231202051 从右向左滚动显示
--   3. 时钟频率: 24MHz
--------------------------------------------------------------------------------

library ieee;
use ieee.std_logic_1164.all;
use ieee.std_logic_unsigned.all;

--------------------------------------------------------------------------------
-- 实体定义
--------------------------------------------------------------------------------
entity dis is
    port(
        clk   : in  std_logic;                      -- 系统时钟 (24MHz, PIN_210)
        seg   : out std_logic_vector(7 downto 0);   -- 段选信号 (a~g + dp, active low)
        dig   : out std_logic_vector(5 downto 0)    -- 位选信号 (6位数码管, active low)
    );
end entity;

--------------------------------------------------------------------------------
-- 架构实现
--------------------------------------------------------------------------------
architecture behavior of dis is

    ----------------------------------------------------------------------------
    -- 计数器信号
    ----------------------------------------------------------------------------
    signal scan_count   : integer range 0 to 4000 := 0;      -- 扫描分频计数 (24MHz/4000 ≈ 6kHz)
    signal scroll_count : integer range 0 to 12000000 := 0;  -- 滚动分频计数 (24MHz/12M = 0.5Hz, 约0.5秒滚动一位)
    signal scan_index   : integer range 0 to 5 := 0;         -- 当前扫描的数码管位置 (0~5)
    signal scroll_index : integer range 0 to 15 := 0;        -- 当前滚动偏移量 (0~15)
    
    ----------------------------------------------------------------------------
    -- 七段数码管编码表 (共阴极, active low)
    -- 编码格式: dp g f e d c b a
    ----------------------------------------------------------------------------
    type seg_array is array (0 to 10) of std_logic_vector(7 downto 0);
    constant seg_data : seg_array := (
        "11000000",  -- 0: 显示数字 0
        "11111001",  -- 1: 显示数字 1
        "10100100",  -- 2: 显示数字 2
        "10110000",  -- 3: 显示数字 3
        "10011001",  -- 4: 显示数字 4
        "10010010",  -- 5: 显示数字 5
        "10000010",  -- 6: 显示数字 6
        "11111000",  -- 7: 显示数字 7
        "10000000",  -- 8: 显示数字 8
        "10010000",  -- 9: 显示数字 9
        "11111111"   -- 10: 空白 (全灭)
    );
    
    ----------------------------------------------------------------------------
    -- 学号数据 (20231202051 + 5个空格用于滚动间隔)
    ----------------------------------------------------------------------------
    type id_array is array (0 to 15) of integer range 0 to 10;
    constant student_id : id_array := (
        2, 0, 2, 3, 1, 2, 0, 2, 0, 5, 1,  -- 学号: 20231202051
        10, 10, 10, 10, 10                 -- 空格填充 (滚动时的间隔)
    );
    
    -- 当前显示缓冲区 (6位数码管对应的显示数据)
    signal display_data : id_array := (10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10);
    
begin

    ----------------------------------------------------------------------------
    -- 主控制进程: 数码管扫描 + 滚动控制
    ----------------------------------------------------------------------------
    process(clk)
    begin
        if rising_edge(clk) then
            
            -- 数码管动态扫描分频 (约6kHz刷新率, 每位约1kHz)
            if scan_count < 4000 then
                scan_count <= scan_count + 1;
            else
                scan_count <= 0;
                -- 循环切换扫描位置 (0 -> 1 -> 2 -> 3 -> 4 -> 5 -> 0)
                if scan_index = 5 then
                    scan_index <= 0;
                else
                    scan_index <= scan_index + 1;
                end if;
            end if;
            
            -- 滚动速度分频 (约0.5Hz, 每0.5秒滚动一位)
            if scroll_count < 12000000 then
                scroll_count <= scroll_count + 1;
            else
                scroll_count <= 0;
                -- 更新滚动偏移量
                if scroll_index = 15 then
                    scroll_index <= 0;
                else
                    scroll_index <= scroll_index + 1;
                end if;
                
                -- 根据滚动偏移量更新显示缓冲区
                for i in 0 to 5 loop
                    display_data(i) <= student_id((scroll_index + i) mod 16);
                end loop;
            end if;
            
        end if;
    end process;

    ----------------------------------------------------------------------------
    -- 数码管输出进程: 生成段选和位选信号
    ----------------------------------------------------------------------------
    process(scan_index, display_data)
    begin
        -- 位选信号 (低电平有效, 一次只选中一位)
        case scan_index is
            when 0      => dig <= "111110";  -- 选中第0位 (最右)
            when 1      => dig <= "111101";  -- 选中第1位
            when 2      => dig <= "111011";  -- 选中第2位
            when 3      => dig <= "110111";  -- 选中第3位
            when 4      => dig <= "101111";  -- 选中第4位
            when 5      => dig <= "011111";  -- 选中第5位 (最左)
            when others => dig <= "111111";  -- 全不选中
        end case;
        
        -- 段选信号 (根据显示数据查表输出)
        if display_data(scan_index) = 10 then
            seg <= seg_data(10);  -- 显示空白
        else
            seg <= seg_data(display_data(scan_index));  -- 显示对应数字
        end if;
    end process;

end architecture;