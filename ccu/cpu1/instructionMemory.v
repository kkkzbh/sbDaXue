module instructionMemory(  // 指令存储器模块定义
    // 根据数据通路图定义输入输出接口
    input  [31:0] addr,    // 输入：32位指令地址
    output [5:0] opCode,   // 输出：6位操作码
    output [4:0] rs, rt, rd,  // 输出：5位寄存器地址（源寄存器rs、rt和目标寄存器rd）
    output [15:0] immediate,  // 输出：16位立即数
    output [4:0] sa,  // 输出：5位移位量
    output [5:0] Func,  // 输出：6位功能码
    output reg[31:0] instruction  // 输出：32位完整指令
    );

    wire [31:0] mem[255:0];  // 定义指令存储器，容量为256个32位字
    
    // 初始化基地址寄存器
    assign mem[0] = 32'b00100100000111100000000000000000;  // addi $30, $0, 0 (初始化$30=0)
    
    // ====== R型指令测试 ======
    // 初始化寄存器
    assign mem[1] = 32'b00100100000000010000000000000101;  // addi $1, $0, 5 ($1=5)
    assign mem[2] = 32'b00100100000000100000000000000111;  // addi $2, $0, 7 ($2=7)
    
    // 1. ADDU测试 - $3 = $1 + $2 = 5 + 7 = 12
    assign mem[3] = 32'b00000000001000100001100000100001;  // addu $3, $1, $2
    assign mem[4] = 32'b10101111110000110000000000010000;  // sw $3, 16($30) (MEM16=12)
    
    // 2. SUBU测试 - $4 = $2 - $1 = 7 - 5 = 2
    assign mem[5] = 32'b00000000010000010010000000100011;  // subu $4, $2, $1
    assign mem[6] = 32'b10101111110001000000000000010001;  // sw $4, 17($30) (MEM17=2)
    
    // 3. SLT测试 - $5 = ($1 < $2) ? 1 : 0 = 1
    assign mem[7] = 32'b00000000001000100010100000101010;  // slt $5, $1, $2
    assign mem[8] = 32'b10101111110001010000000000010010;  // sw $5, 18($30) (MEM18=1)
    
    // 4. AND测试 - $6 = $1 & $2 = 5 & 7 = 5 (二进制: 101 & 111 = 101)
    assign mem[9] = 32'b00000000001000100011000000100100;  // and $6, $1, $2
    assign mem[10] = 32'b10101111110001100000000000010011;  // sw $6, 19($30) (MEM19=5)
    
    // 5. NOR测试 - $7 = ~($1 | $2) = ~(5 | 7) = ~(7) = -8 (32位补码)
    assign mem[11] = 32'b00000000001000100011100000100111;  // nor $7, $1, $2
    assign mem[12] = 32'b10101111110001110000000000010100;  // sw $7, 20($30) (MEM20=-8)
    
    // 6. OR测试 - $8 = $1 | $2 = 5 | 7 = 7 (二进制: 101 | 111 = 111)
    assign mem[13] = 32'b00000000001000100100000000100101;  // or $8, $1, $2
    assign mem[14] = 32'b10101111110010000000000000010101;  // sw $8, 21($30) (MEM21=7)
    
    // 7. XOR测试 - $9 = $1 ^ $2 = 5 ^ 7 = 2 (二进制: 101 ^ 111 = 010)
    assign mem[15] = 32'b00000000001000100100100000100110;  // xor $9, $1, $2
    assign mem[16] = 32'b10101111110010010000000000010110;  // sw $9, 22($30) (MEM22=2)
    
    // 8. SLL测试 - $10 = $1 << 2 = 5 << 2 = 20
    assign mem[17] = 32'b00000000000000010101000010000000;  // sll $10, $1, 2
    assign mem[18] = 32'b10101111110010100000000000010111;  // sw $10, 23($30) (MEM23=20)
    
    // 9. SRL测试 - $11 = $2 >> 1 = 7 >> 1 = 3
    assign mem[19] = 32'b00000000000000100101100001000010;  // srl $11, $2, 1
    assign mem[20] = 32'b10101111110010110000000000011000;  // sw $11, 24($30) (MEM24=3)
    
    // ====== I型指令测试 ======
    // 10. ADDIU测试 - $12 = $0 + 100 = 100
    assign mem[21] = 32'b00100100000011000000000001100100;  // addiu $12, $0, 100
    assign mem[22] = 32'b10101111110011000000000000011001;  // sw $12, 25($30) (MEM25=100)
    
    // 11. SLTI测试 - $13 = ($1 < 10) ? 1 : 0 = 1
    assign mem[23] = 32'b00101000001011010000000000001010;  // slti $13, $1, 10
    assign mem[24] = 32'b10101111110011010000000000011010;  // sw $13, 26($30) (MEM26=1)
    
    // 12. LW测试 - 从MEM16中加载值到$14
    assign mem[25] = 32'b10001111110011100000000000010000;  // lw $14, 16($30) (从MEM16加载值12)
    assign mem[26] = 32'b10101111110011100000000000011011;  // sw $14, 27($30) (MEM27=12)
    
    // ====== 跳转和分支指令测试 ======
    // 13. BEQ测试 - 如果$1=$1，跳过2条指令（跳过设置$15=1）
    assign mem[27] = 32'b00100100000011110000000000000000;  // addi $15, $0, 0 ($15=0初始化)
    assign mem[28] = 32'b00010000001000010000000000000010;  // beq $1, $1, 2 (如果$1=$1，跳过2条指令)
    assign mem[29] = 32'b00100100000011110000000000000001;  // addi $15, $0, 1 (这条指令会被跳过)
    assign mem[30] = 32'b00100100000100000000000000000001;  // addi $16, $0, 1 (这条指令会被跳过)
    assign mem[31] = 32'b10101111110011110000000000011100;  // sw $15, 28($30) (MEM28应该等于0)
    
    // 14. BNE测试 - 如果$1!=$2，跳过2条指令（跳过设置$17=1）
    assign mem[32] = 32'b00100100000100010000000000000000;  // addi $17, $0, 0 ($17=0初始化)
    assign mem[33] = 32'b00010100001000100000000000000010;  // bne $1, $2, 2 (如果$1!=$2，跳过2条指令)
    assign mem[34] = 32'b00100100000100010000000000000001;  // addi $17, $0, 1 (这条指令会被跳过)
    assign mem[35] = 32'b00100100000100100000000000000001;  // addi $18, $0, 1 (这条指令会被跳过)
    assign mem[36] = 32'b10101111110100010000000000011101;  // sw $17, 29($30) (MEM29应该等于0)
    
    // 15. J测试 - 直接跳转到指令40
    assign mem[37] = 32'b00001000000000000000000000101000;  // j 40 (跳到指令40)
    assign mem[38] = 32'b00100100000100110000000000000001;  // addi $19, $0, 1 (这条指令会被跳过)
    assign mem[39] = 32'b00100100000101000000000000000001;  // addi $20, $0, 1 (这条指令会被跳过)
    
    // 跳转目标
    assign mem[40] = 32'b00100100000101010000000000000101;  // addi $21, $0, 5 ($21=5)
    assign mem[41] = 32'b10101111110101010000000000011110;  // sw $21, 30($30) (MEM30=5)
    
    // 程序终止指令
    assign mem[42] = 32'b11111111111111111111111111111111;  // 终止指令
    
    // 填充其余空间
    genvar i;
    generate
        for (i = 43; i < 256; i = i + 1) begin
            assign mem[i] = 32'b00000000000000000000000000000000; // NOP指令填充
        end
    endgenerate
    
    always @(*) // 组合逻辑，任何输入变化都会触发
    begin
         instruction = mem[addr];  // 根据地址读取指令
    end
    
    // 输出指令的各个字段
    assign opCode = instruction[31:26];  // 将指令的高6位作为操作码输出
    assign rs = instruction[25:21];  // 将指令的25-21位作为rs寄存器地址输出
    assign rt = instruction[20:16];  // 将指令的20-16位作为rt寄存器地址输出
    assign rd = instruction[15:11];  // 将指令的15-11位作为rd寄存器地址输出
    assign immediate = instruction[15:0];  // 将指令的低16位作为立即数输出
    assign sa = instruction[10:6];  // 将指令的10-6位作为移位量输出
    assign Func=instruction[5:0];  // 将指令的低6位作为功能码输出

endmodule 