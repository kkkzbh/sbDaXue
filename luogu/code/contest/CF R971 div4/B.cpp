fun solve()
{
    int n;
    std::cin >> n;
    std::array<char,4> a;
    std::vector<int> b;
    while(n--) {
        std::copy_n(std::istream_iterator<char>{ std::cin },4,a.begin());
        b.push_back(std::distance(a.begin(),std::ranges::find(a,'#')) + 1);
    }
    std::ranges::copy(b | reverse,std::ostream_iterator<int>{ std::cout," " });
    std::cout << '\n';
}

fun main() -> int
{
    std::ios::sync_with_stdio(false),std::cin.tie(nullptr);
    int t;
    std::cin >> t;
    while(t--) {
        std::invoke(solve);
    }
}